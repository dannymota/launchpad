#!/usr/bin/env node
// Writes the files the Impeccable design skill reads before it touches a screen, from what
// the repository already holds, so nobody keeps a second copy by hand:
//
//   DESIGN.md                the look: the brand (packages/theme/src/brand.ts) and the built theme
//   PRODUCT.md               who the product is for and what it does: product/brief.md
//   apps/mobile/PRODUCT.md   the same, for the app, which follows each phone's own conventions
//
// PRODUCT.md waits for the brief: before /start there is none to write from.
//
//   npm run design:context              write them (`npm run theme` also does, after a rebuild)
//   npm run design:context -- --check   write nothing; fail when one on disk is out of date
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { resolvedTokens, tokenValue } from "./build-tokens.mjs";
import { loadProduct, ROOT } from "./lib/product.mjs";

const NOTE = (from) => `<!-- Generated by \`npm run design:context\` from ${from}. Edit those, then run it again. -->`;

/** A brief's sections: heading → the text under it. */
export function sectionsOf(brief) {
  const out = {};
  for (const part of brief.split(/^## /m).slice(1)) {
    const [heading, ...body] = part.split("\n");
    out[heading.trim()] = body.join("\n").trim();
  }
  return out;
}

/** What holds on each platform however the product changes. It is the template's, not the brief's. */
const CONSTRAINTS = {
  web: [
    "The interface is built only from Astryx components (`@astryxdesign/core`). No hand-written CSS, no `<div>` or `<span>`, no inline styles, no literal colour, font or pixel value in a page.",
    "Colours, corner radii and the typeface are set in one file, `packages/theme/src/brand.ts`. `npm run theme` builds the theme and DESIGN.md from it. Changing the look means changing that file, never a page.",
    "A page starts from an Astryx template (`npx astryx build`, `npx astryx template`) and keeps its frame. Read a component's props (`npx astryx component <Name>`) before using it.",
    "Pages are server components on Cloudflare Workers (vinext). Where a page lives decides who can open it: see `.claude/rules/web.md`.",
  ],
  adaptive: [
    "One Expo codebase for iOS and Android. Each platform keeps its own controls, navigation and system typeface; platform code lives in `apps/mobile/src/platform` and screens reach it only through that folder.",
    "Colours and radii come from `@app/theme/native`, generated from the same brand file as the website. A screen never sets a colour.",
    "`.claude/rules/mobile.md` and the Appllama design skill set the bar for a screen. Where they differ from a general guideline, they win.",
  ],
};

const ACCESSIBILITY =
  "WCAG 2.2 AA. Text contrast is tested in both colour schemes (`packages/theme/tests`), every action works from the keyboard, and headings keep their order.";

/**
 * PRODUCT.md, in the layout Impeccable reads (its `init` reference): product truth only,
 * nothing about the look. `platform` is "web" or "adaptive".
 */
export function productMd({ product, brief, platform }) {
  const from = sectionsOf(brief);
  const purpose = [from["What it is"], from["The main thing people do"]].filter(Boolean).join("\n\n");
  const constraints = [
    from["What it is not"] && `What it is not: ${from["What it is not"].replace(/\s*\n\s*/g, " ")}`,
    ...CONSTRAINTS[platform],
  ].filter(Boolean);
  const blocks = [
    ["Platform", platform],
    ["Users", from["Who it is for"]],
    ["Product Purpose", purpose],
    ["Capabilities and Constraints", constraints.map((line) => `- ${line}`).join("\n")],
    [
      "Brand Commitments",
      [
        `- Name: ${product.name}. Tagline: "${product.tagline}"`,
        from.Voice && `- Voice: ${from.Voice.replace(/\s*\n\s*/g, " ")}`,
      ]
        .filter(Boolean)
        .join("\n"),
    ],
    [
      "Evidence on Hand",
      from.Proof ||
        "Nothing is on record: no testimonials, customer names, usage numbers or press. Do not invent any. Ask the owner, and add what is real to the brief under `## Proof`.",
    ],
    ["Accessibility & Inclusion", ACCESSIBILITY],
  ];
  const body = blocks
    .filter(([, text]) => text)
    .map(([heading, text]) => `## ${heading}\n\n${text}`)
    .join("\n\n");
  return `# Product\n\n<!-- impeccable:product-schema 1 -->\n${NOTE("product/brief.md and product/product.config.ts")}\n\n${body}\n`;
}

const kebab = (name) => name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

/** The type roles DESIGN.md names, and the Astryx role each takes its values from. */
const TYPE_ROLES = { display: "display-2", headline: "heading-1", title: "heading-3", body: "body", label: "label" };

/** Astryx names its weights; their values live in its base stylesheet, not in a theme. */
const WEIGHTS = { normal: 400, medium: 500, semibold: 600, bold: 700 };

function weightOf(themeTokens, name) {
  const value = String(themeTokens[name] ?? "");
  const named = /^var\(--font-weight-(\w+)\)$/.exec(value.trim())?.[1];
  const weight = named ? WEIGHTS[named] : Number(value);
  if (!weight) throw new Error(`${name} is "${value}": expected a font weight.`);
  return weight;
}

/** The theme's values in the shape DESIGN.md's frontmatter takes. */
export function designTokens(themeTokens) {
  const { color, radius } = resolvedTokens(themeTokens);
  const colors = {};
  for (const [role, value] of Object.entries(color.light)) colors[kebab(role)] = value;
  for (const [role, value] of Object.entries(color.dark)) colors[`${kebab(role)}-dark`] = value;
  const typography = {};
  for (const [role, source] of Object.entries(TYPE_ROLES)) {
    const family = role === "body" || role === "label" ? "body" : "heading";
    typography[role] = {
      fontFamily: tokenValue(themeTokens, `--font-family-${family}`),
      fontSize: tokenValue(themeTokens, `--text-${source}-size`),
      fontWeight: weightOf(themeTokens, `--text-${source}-weight`),
      lineHeight: Number(tokenValue(themeTokens, `--text-${source}-leading`)),
    };
  }
  const rounded = Object.fromEntries(Object.entries(radius).map(([role, px]) => [role, `${px}px`]));
  return { colors, typography, rounded };
}

/** A small YAML writer: nested maps of strings and numbers, which is all the frontmatter holds. */
function yaml(value, indent = "") {
  return Object.entries(value)
    .map(([key, item]) =>
      typeof item === "object"
        ? `${indent}${key}:\n${yaml(item, `${indent}  `)}`
        : `${indent}${key}: ${typeof item === "number" ? item : JSON.stringify(item)}`,
    )
    .join("\n");
}

/**
 * DESIGN.md, in the format Impeccable and other tools read: tokens in the frontmatter, then
 * the eight sections in their fixed order. The tokens are the brand's; the prose says how this
 * template applies them, which is what keeps a design pass inside the component library.
 */
export function designMd({ product, brand, themeTokens }) {
  const tokens = designTokens(themeTokens);
  const { colors, typography, rounded } = tokens;
  const pair = (role) => `${colors[role]} in light, ${colors[`${role}-dark`]} in dark`;
  const type = (role) =>
    `${typography[role].fontWeight}, ${typography[role].fontSize}, line height ${typography[role].lineHeight}`;
  const families = [...new Set([brand.font.heading, brand.font.body])];
  return `---
${yaml({ name: product.name, description: product.tagline, ...tokens })}
---

${NOTE("packages/theme/src/brand.ts and the built theme")}

# Design System: ${product.name}

## Overview

${brand.character}

Every screen is assembled from Astryx components. A page never sets a colour, a typeface, a radius or a pixel value: all of them come from the theme built from \`packages/theme/src/brand.ts\`. To change the look, change that file and run \`npm run theme\`; this document follows.

**Key Characteristics:**

- One accent colour on neutral surfaces.
- Light and dark from the same pairs of values, never a separate dark design.
- Standard controls, used as the component library ships them.
- Dense information as rows, not as cards.

## Colors

One accent, and neutrals that carry everything else. Each role has a light and a dark value; the dark one is the \`-dark\` key in the frontmatter.

### Primary

- **Accent** (${pair("accent")}): the main action on a screen, links, the focus ring, the current selection. Nothing decorative.
- **Accent, muted** (${pair("accent-muted")}): a quiet fill for a selected row or a highlighted note.
- **Accent text** (${pair("accent-text")}): accent-coloured text on the page background, darker than the fill so it reads at small sizes.
- **On accent** (${pair("on-accent")}): text and icons on top of the accent.

### Neutral

- **Background** (${pair("background")}) and **Surface** (${pair("surface")}): the page, and what sits on it.
- **Text** (${pair("text")}), **Secondary text** (${pair("text-secondary")}), **Disabled text** (${pair("text-disabled")}).
- **Border** (${pair("border")}) and **Strong border** (${pair("border-strong")}).
- **Danger** (${pair("danger")}) and **Success** (${pair("success")}): state, only where it carries meaning.

### Named Rules

**The One Accent Rule.** There is one accent colour. A second accent, a gradient or a tint invented for one screen is a change to the brand file, not to a page.

**The No Literal Colour Rule.** No page or component writes a hex, rgb or oklch value. A colour is reached through a component's own props.

## Typography

**Display Font:** ${brand.font.heading} (with the system sans-serif behind it)
**Body Font:** ${brand.font.body} (with the system sans-serif behind it)

**Character:** ${families.length === 1 ? `One family, ${families[0]}, for headings, labels, body and data.` : `${brand.font.heading} for headings, ${brand.font.body} for everything else.`} The scale is fixed, not fluid.

### Hierarchy

- **Display** (${type("display")}): the one headline of a public page.
- **Headline** (${type("headline")}): a page's title.
- **Title** (${type("title")}): a section inside a page.
- **Body** (${type("body")}): running text and data. Prose stays within 65 to 75 characters a line.
- **Label** (${type("label")}): controls and field labels.

### Named Rules

**The Component Sets The Size Rule.** Text is sized by the component and level that holds it (\`Heading level\`, \`Text size\`), never by a font-size on the page.

## Layout

Layout comes from Astryx layout components and their props (\`gap\`, \`padding\`, \`maxWidth\`, alignment). A page starts from an Astryx template and keeps its frame, gap and padding. Narrow screens are handled by the same components; a page adds no breakpoint of its own.

## Elevation & Depth

Flat at rest. The theme has three shadow steps, and the component library uses them for what floats above the page: menus, popovers, dialogs. A page never writes a shadow.

## Shapes

Four radii, by what the element is: ${rounded.inner} for small parts inside a control, ${rounded.element} for controls, ${rounded.container} for cards and panels, ${rounded.page} for page-level surfaces. Borders are one pixel in the border colour. No coloured side stripe on a card or a row.

## Components

Astryx provides them. Find one with \`npx astryx search "<words>"\` and read its props with \`npx astryx component <Name>\` before using it.

### Buttons

- **Primary:** accent fill with on-accent text. At most one on a screen.
- **Secondary and ghost:** neutral. A destructive action uses the danger variant and asks first.

### Cards / Containers

- A card groups one thing. Cards are never nested, and a list is never a stack of cards.

### Inputs / Fields

- Every field has a visible label. An error names the problem and the way out, on the field.

### Lists and tables

- Dense data is rows: \`Table\`, or \`List\` with \`ListItem\`. A count is a \`Badge\`; a status is a \`Token\`.

## Do's and Don'ts

### Do:

- **Do** build from Astryx components and templates, and keep a template's frame.
- **Do** change the look in \`packages/theme/src/brand.ts\`, then run \`npm run theme\`.
- **Do** give every screen its empty, loading and error states.
- **Do** write controls that name their action, in the product's own words.

### Don't:

- **Don't** write \`<div>\`, \`<span>\`, \`style={{}}\`, a stylesheet, or a utility class with an arbitrary value.
- **Don't** add a second accent colour, a gradient, a glow or a new typeface in a page.
- **Don't** put a small uppercase label above a heading, or number the sections.
- **Don't** invent a testimonial, a customer, a number or a claim the brief does not hold.
`;
}

async function loadBrand(root) {
  const bundled = await build({
    entryPoints: [join(root, "packages/theme/src/brand.ts")],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
    logLevel: "silent",
  });
  const source = Buffer.from(bundled.outputFiles[0].text).toString("base64");
  return (await import(`data:text/javascript;base64,${source}`)).brand;
}

/** Every file this script owns, by path from the root: its text, or null when it has nothing to write from. */
export async function contextFiles(root = ROOT) {
  const { product } = await loadProduct(root);
  const brand = await loadBrand(root);
  const { brandTheme } = await import(pathToFileURL(join(root, "apps/web/src/themes/brand/brand.js")).href);
  const briefPath = join(root, "product/brief.md");
  const brief = existsSync(briefPath) ? readFileSync(briefPath, "utf8") : null;
  const files = {
    "DESIGN.md": designMd({ product, brand, themeTokens: brandTheme.tokens }),
    "PRODUCT.md": brief && productMd({ product, brief, platform: "web" }),
  };
  if (existsSync(join(root, "apps/mobile"))) {
    files["apps/mobile/PRODUCT.md"] = brief && productMd({ product, brief, platform: "adaptive" });
  }
  return files;
}

async function main(argv) {
  const check = argv.includes("--check");
  const stale = [];
  for (const [path, text] of Object.entries(await contextFiles())) {
    // Nothing to write from yet (no brief): a file someone wrote by hand is left alone.
    if (text === null) continue;
    const file = join(ROOT, path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (current === text) continue;
    if (check) stale.push(path);
    else {
      writeFileSync(file, text);
      console.log(`Wrote ${path}`);
    }
  }
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run \`npm run design:context\`.`);
    process.exit(1);
  }
  if (check) console.log("The design context files are up to date.");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
