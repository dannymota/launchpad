#!/usr/bin/env node
// Writes the brand's colours and radii as plain values, per colour scheme, from the built web
// theme. The contrast tests read them.
// So does the mobile app, so iOS and Android can never show a different brand from the website.
//   apps/web/src/themes/brand/brand.js   (built by `astryx theme build`)
//     → packages/theme/src/generated/tokens.ts
// Run through `npm run theme`, which builds the web theme first. `--check` writes nothing and
// fails when the file on disk is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(root, "packages/theme/src/generated/tokens.ts");

/** Role → the web token it takes its value from. */
export const COLOR_ROLES = {
  background: "--color-background-body",
  surface: "--color-background-surface",
  card: "--color-background-card",
  muted: "--color-background-muted",
  text: "--color-text-primary",
  textSecondary: "--color-text-secondary",
  textDisabled: "--color-text-disabled",
  border: "--color-border",
  borderStrong: "--color-border-emphasized",
  accent: "--color-accent",
  onAccent: "--color-on-accent",
  accentMuted: "--color-accent-muted",
  accentText: "--color-text-accent",
  danger: "--color-text-error",
  success: "--color-text-success",
};
export const RADIUS_ROLES = {
  inner: "--radius-inner",
  element: "--radius-element",
  container: "--radius-container",
  page: "--radius-page",
};

/** A token's value with every var() followed to its end. */
export function tokenValue(tokens, name, depth = 0) {
  const value = tokens[name];
  if (typeof value !== "string") throw new Error(`The built theme has no ${name} token.`);
  const reference = /^var\((--[\w-]+)\)$/.exec(value.trim());
  if (!reference) return value.trim();
  if (depth > 8) throw new Error(`${name} refers to itself.`);
  return tokenValue(tokens, reference[1], depth + 1);
}

const HEX = /^#(?:[0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;

/** "light-dark(#fff, #000)" → ["#fff", "#000"]; a single colour is used for both. */
function colorPair(tokens, name) {
  const value = tokenValue(tokens, name);
  const match = /^light-dark\(\s*([^,]+?)\s*,\s*([^,]+?)\s*\)$/.exec(value);
  const pair = match ? [match[1], match[2]] : [value, value];
  for (const color of pair) {
    if (!HEX.test(color)) throw new Error(`${name} is "${value}": the native theme needs plain hex colours.`);
  }
  return pair.map((color) => color.toLowerCase());
}

function pixels(tokens, name) {
  const value = tokenValue(tokens, name);
  const match = /^(-?\d*\.?\d+)(rem|px)$/.exec(value);
  if (!match) throw new Error(`${name} is "${value}": the native theme needs a rem or px length.`);
  return Math.round(Number(match[1]) * (match[2] === "rem" ? 16 : 1) * 100) / 100;
}

/** The resolved tokens for a built web theme's token map. */
export function resolvedTokens(tokens) {
  const light = {};
  const dark = {};
  for (const [role, name] of Object.entries(COLOR_ROLES)) [light[role], dark[role]] = colorPair(tokens, name);
  const radius = Object.fromEntries(Object.entries(RADIUS_ROLES).map(([role, name]) => [role, pixels(tokens, name)]));
  return { color: { light, dark }, radius };
}

export function render(resolved) {
  return `// Generated by \`npm run theme\` from apps/web/src/themes/brand. Do not edit: change
// packages/theme/src/brand.ts and run it again.
export const tokens = ${JSON.stringify(resolved, null, 2)} as const;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { brandTheme } = await import(resolve(root, "apps/web/src/themes/brand/brand.js"));
  const next = render(resolvedTokens(brandTheme.tokens));
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {}
    if (current !== next) {
      console.error("packages/theme/src/generated/tokens.ts is out of date. Run `npm run theme`.");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, next);
    console.log("Wrote packages/theme/src/generated/tokens.ts");
  }
}
