#!/usr/bin/env node
// Before a command runs or a file is written: refuse the few actions that are never right
// in this repository, and say what to do instead. Rules that only need judgement live in
// AGENTS.md; these are the ones a mistake cannot be allowed to make.
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED = [
  [
    /^packages\/backend\/migrations\//,
    "Migrations are generated. Edit packages/backend/src/db/schema, then run `npm run db:generate`.",
  ],
  [
    /^packages\/backend\/src\/db\/schema\/auth\.ts$/,
    "This file is generated by Better Auth: `npm run auth:generate -w @app/backend`.",
  ],
  [
    /^packages\/theme\/src\/(generated\/|palette\.ts$)/,
    "This file is generated. Edit packages/theme/src/brand.ts or palette.config.json, then run `npm run theme`.",
  ],
  [
    /^apps\/web\/src\/themes\/brand\/brand\.(js|css|d\.ts)$/,
    "This file is built by `npm run theme` from brandTheme.ts and packages/theme/src/brand.ts.",
  ],
];
const SECRET_FILE = /(^|\/)(\.dev\.vars|\.env)(\.(?!example$)[^/]*)?$/;

/** Why writing `file` (relative to the repository) is refused, or null. */
export function refuseWrite(file) {
  if (SECRET_FILE.test(file)) {
    return "Secret files are never written by an agent. Local settings are created at session start; deployed secrets are set by `npm run setup`.";
  }
  for (const [pattern, reason] of GENERATED) if (pattern.test(file)) return reason;
  return null;
}

/** The owner of a GitHub remote URL or `owner/repo` string, lowercased. */
const ownerOf = (text) =>
  /(?:github\.com[:/]|^)([\w.-]+)\/[\w.-]+?(?:\.git)?$/.exec(text.trim())?.[1]?.toLowerCase() ?? null;

/** Why running `command` is refused, or null. `originUrl` is this repository's origin remote. */
export function refuseCommand(command, originUrl = "") {
  // Each part of a compound command is judged on its own.
  for (const part of command.split(/&&|\|\||;|\n|\|/)) {
    const words = part.trim().split(/\s+/);
    const at = (name) => words.indexOf(name);
    const text = words.join(" ");

    if (/\bnpm audit fix\b.*--force/.test(text)) {
      return "`npm audit fix --force` rewrites pinned versions across major releases. Upgrade the one package by hand instead.";
    }
    const deploys =
      /\b(wrangler|vinext-cloudflare)\b.*\bdeploy\b/.test(text) ||
      /\bwrangler\b.*\bversions (upload|deploy)\b/.test(text);
    // A dry run builds the bundle and uploads nothing.
    if (deploys && !words.includes("--dry-run")) {
      return "Deploy through `npm run deploy -- <staging|production>`: it applies migrations first and refuses when Cloudflare Access does not match the access map.";
    }
    if (/\bwrangler\b.*\bd1\b.*\b(execute|migrations apply)\b.*--remote\b/.test(text)) {
      return "Remote databases change only through the deploy script, which applies generated migrations. For a one-off query, ask the owner.";
    }
    if (words[0] === "git" && at("push") > 0) {
      const target = words.slice(at("push") + 1).find((word) => !word.startsWith("-"));
      if (target && target !== "origin" && (target.includes("/") || target.includes(":") || target.includes("@"))) {
        return "Push only to this repository's own remote (origin).";
      }
    }
    if (words[0] === "gh" && words[1] === "pr" && words[2] === "create") {
      const repo = words[at("--repo") + 1] ?? words[at("-R") + 1];
      const named = at("--repo") > 0 || at("-R") > 0 ? ownerOf(repo ?? "") : null;
      const mine = ownerOf(originUrl);
      if (named && mine && named !== mine) {
        return "Never open a pull request against a repository the owner does not own without their approval in this session.";
      }
    }
  }
  return null;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();
  let payload = {};
  try {
    payload = JSON.parse(readFileSync(0, "utf8"));
  } catch {
    process.exit(0);
  }
  let reason = null;
  if (payload.tool_name === "Bash" && typeof payload.tool_input?.command === "string") {
    let origin = "";
    try {
      origin = execFileSync("git", ["remote", "get-url", "origin"], {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      });
    } catch {}
    reason = refuseCommand(payload.tool_input.command, origin);
  } else if (typeof payload.tool_input?.file_path === "string") {
    const file = relative(root, resolve(root, payload.tool_input.file_path)).split("\\").join("/");
    if (!file.startsWith("..")) reason = refuseWrite(file);
  }
  if (reason) {
    console.log(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: "PreToolUse",
          permissionDecision: "deny",
          permissionDecisionReason: reason,
        },
      }),
    );
  }
}
